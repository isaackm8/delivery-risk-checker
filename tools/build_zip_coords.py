"""Build data/zip-coords.js from the US Census ZCTA Gazetteer file.

Source: https://www2.census.gov/geo/docs/maps-data/data/gazetteer/
        2025_Gazetteer/2025_Gaz_zcta_national.zip

Usage:
    python tools/build_zip_coords.py path/to/2025_Gaz_zcta_national.txt data/zip-coords.js
"""

import csv
import json
import sys


def main(src_path, out_path):
    coords = {}
    with open(src_path, newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f, delimiter="|")
        # Header names in the Census file sometimes carry trailing spaces.
        reader.fieldnames = [name.strip() for name in reader.fieldnames]
        for row in reader:
            zip_code = row["GEOID"].strip()
            if len(zip_code) != 5 or not zip_code.isdigit():
                continue
            lat = round(float(row["INTPTLAT"]), 3)
            lon = round(float(row["INTPTLONG"]), 3)
            coords[zip_code] = [lat, lon]

    body = json.dumps(coords, separators=(",", ":"), sort_keys=True)
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/build_zip_coords.py from the US Census 2025 ZCTA Gazetteer.\n")
        f.write("// ZIP -> [latitude, longitude]. Do not edit by hand.\n")
        f.write("window.ZIP_COORDS = " + body + ";\n")

    print(f"Wrote {len(coords)} ZIPs to {out_path}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
